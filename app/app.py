"""Food classifier demo: upload/camera -> prediction -> Grad-CAM + nearest neighbours + latency.

    streamlit run app/app.py
"""
import os
import platform
import sys
import time

import numpy as np
import streamlit as st
import torch
from PIL import Image

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src"))

from common import A1_CHECKPOINT, CLASSES, DEVICE, RESULTS_DIR, embed, load_model
from explain import gradcam_overlay, preprocess

APP_MODEL = os.path.join(RESULTS_DIR, "app_model.pt")
MODEL_PATH = APP_MODEL if os.path.exists(APP_MODEL) else A1_CHECKPOINT
INDEX_PATH = os.path.join(RESULTS_DIR, "index.npz")
ASSETS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "assets")
SYN_DIR = os.path.join(ASSETS, "synthetic")

st.set_page_config(page_title="Food classifier", layout="wide")


@st.cache_resource
def get_model():
    return load_model(MODEL_PATH)


@st.cache_resource
def get_index():
    d = np.load(INDEX_PATH, allow_pickle=True)
    return d["feats"], d["labels"], d["paths"]


def thumb(path, label):
    """Thumbnail shipped with the app (full dataset is not in git)."""
    name = os.path.splitext(os.path.basename(str(path)))[0] + ".jpg"
    return os.path.join(ASSETS, "train", CLASSES[label], name)


model = get_model()
feats, labels, paths = get_index()

st.title("Food classifier: burger / hotdog / pizza / sandwich / sushi")
with st.sidebar:
    st.subheader("Environment")
    st.write(f"Device: **{DEVICE}**  \nTorch {torch.__version__}  \n{platform.platform()}")
    st.write(f"Model: `{os.path.basename(MODEL_PATH)}`")
    st.caption("Latency = forward pass only (model warmed up, mean of 10 runs).")
    st.subheader("Responsible use")
    st.caption("Images in the 'Synthetic' tab were generated by SD-Turbo and are labelled as such. "
               "Do not upload photos of people without consent; uploads are processed in memory "
               "and not stored.")

tab_demo, tab_joke, tab_syn = st.tabs(["Predict & explain", "Hotdog or Not", "Synthetic training images"])

with tab_demo:
    c1, c2 = st.columns(2)
    up = c1.file_uploader("Upload a food photo", type=["jpg", "jpeg", "png", "webp"])
    cam = c2.camera_input("...or take a photo")
    src = up or cam
    if src is not None:
        img = Image.open(src).convert("RGB")
        x = preprocess(img).to(DEVICE)

        with torch.no_grad():
            model(x)  # warm-up
            times = []
            for _ in range(10):
                t = time.perf_counter()
                logits = model(x)
                if DEVICE.type == "mps":
                    torch.mps.synchronize()
                times.append((time.perf_counter() - t) * 1000)
            probs = torch.softmax(logits, 1)[0].cpu().numpy()
            q = embed(model, x).cpu().numpy()[0]
        q /= np.linalg.norm(q) + 1e-12
        pred = int(probs.argmax())

        st.header(f"Prediction: {CLASSES[pred]} ({probs[pred]:.0%})")
        st.caption(f"Average inference time: {np.mean(times):.1f} ms on {DEVICE}")
        a, b, c = st.columns(3)
        a.image(img, caption="Input", width="stretch")
        overlay, _ = gradcam_overlay(model, img, pred)
        b.image(overlay, caption=f"Grad-CAM for '{CLASSES[pred]}'", width="stretch")
        c.bar_chart({k: float(v) for k, v in zip(CLASSES, probs)})

        st.subheader("Nearest training images (cosine similarity in feature space)")
        sims = feats @ q
        top = np.argsort(-sims)[:5]
        for col, i in zip(st.columns(5), top):
            col.image(thumb(paths[i], labels[i]), caption=f"{CLASSES[labels[i]]}  {sims[i]:.2f}", width="stretch")

with tab_joke:
    st.caption("A joke mode inspired by the 'Not Hotdog' gag from the TV show Silicon Valley. "
               "Same model as the other tab: 'hotdog' if the hotdog class wins, otherwise 'not hotdog'. "
               "It has only seen burgers, pizza, sandwiches and sushi, so it can be confidently wrong "
               "on anything else (shoes, bananas...).")
    jf = st.file_uploader("Upload anything", type=["jpg", "jpeg", "png", "webp"], key="joke")
    if jf is not None:
        jimg = Image.open(jf).convert("RGB")
        with torch.no_grad():
            jp = torch.softmax(model(preprocess(jimg).to(DEVICE)), 1)[0].cpu().numpy()
        hot = CLASSES.index("hotdog")
        if int(jp.argmax()) == hot:
            st.success(f"HOTDOG!  ({jp[hot]:.0%})")
        else:
            st.error(f"NOT HOTDOG.  (looks like {CLASSES[int(jp.argmax())]}; hotdog probability {jp[hot]:.0%})")
        j1, j2 = st.columns(2)
        j1.image(jimg, width="stretch")
        j2.image(gradcam_overlay(model, jimg, hot)[0], caption="Where it looks for 'hotdog'",
                 width="stretch")

with tab_syn:
    st.warning("SYNTHETIC MEDIA: every image below was generated by a text-to-image model "
               "(SD-Turbo). None is a real photograph.")
    shown = False
    for cls in CLASSES:
        d = os.path.join(SYN_DIR, cls)
        if os.path.isdir(d):
            files = sorted(os.listdir(d))[:5]
            if files:
                shown = True
                st.markdown(f"**{cls}**")
                for col, f in zip(st.columns(5), files):
                    col.image(os.path.join(d, f), caption="synthetic", width="stretch")
    if not shown:
        st.info("No accepted synthetic images yet. Run src/build_app_assets.py.")
