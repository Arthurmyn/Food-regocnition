"""Aggregate A2 runs and comparison artifacts into results/a2/summary.md and summary.json."""
import glob
import json
import os
from collections import defaultdict
from decimal import Decimal, ROUND_HALF_UP

import numpy as np

from common import CLASSES, RESULTS_DIR

A1_RESULTS_DIR = os.path.join(os.path.dirname(RESULTS_DIR), "a1")


def read_json(path):
    with open(path) as f:
        return json.load(f)


def percent(value):
    rounded = (Decimal(str(value)) * 100).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP)
    return f"{rounded:.1f}%"


def metric_row(name, data, detail):
    return f"| {name} | {percent(data['accuracy'])} | {percent(data['f1_macro'])} | {detail} |"

runs = defaultdict(list)
for p in sorted(glob.glob(os.path.join(RESULTS_DIR, "runs", "*.json"))):
    r = read_json(p)
    runs[r["name"]].append(r)

def ms(v):
    return f"{np.mean(v):.3f} ± {np.std(v):.3f}"

lines = [
    "# A2 metrics summary",
    "",
    "Generated by `python3 src/aggregate.py`. Scores below use the fixed real-image test split "
    "(79 images) unless stated otherwise.",
    "",
    "## A1 baselines and A2 linear-probe comparison",
    "",
    "These are single fitted models, not repeated-seed estimates. The deployed probe is fit on "
    "train + validation; the training-only probe is used for the clean comparison with synthetic "
    "augmentation.",
    "",
    "| Model | Test accuracy | Test macro-F1 | Fit / notes |",
    "|---|---:|---:|---|",
]
a1 = read_json(os.path.join(A1_RESULTS_DIR, "model_comparison.json"))
probe = read_json(os.path.join(RESULTS_DIR, "linear_probe_metrics.json"))
lines.append(metric_row(
    "A1 HOG + RBF-SVM",
    {"accuracy": a1["svm_test"]["accuracy"], "f1_macro": a1["svm_test"]["f1_macro"]},
    "375 real train images",
))
lines.append(metric_row(
    "A1 fine-tuned EfficientNet-B0",
    {"accuracy": a1["efficientnet_test"]["accuracy"], "f1_macro": a1["efficientnet_test"]["f1_macro"]},
    "375 real train images",
))
lines.append(metric_row(
    "A2 frozen ImageNet probe",
    probe["probe_train_only"]["test"],
    "train-only fit; validation selected C=0.1",
))
lines.append(metric_row(
    "A2 deployed frozen ImageNet probe",
    probe["probe_deployed_train_plus_val"]["test"],
    "refit on train + validation; this is the app checkpoint",
))

lines.extend([
    "",
    "## Frozen-feature probe synthetic-data check",
    "",
    "Single fit per condition. Synthetic images are added to the 375-image real training split; "
    "test images remain real and untouched.",
    "",
    "| Training data | Test accuracy | Test macro-F1 |",
    "|---|---:|---:|",
])
probe_synthetic = probe["probe_plus_synthetic"]
for name in ("real_only (train)", "real+all_synthetic", "real+filtered_synthetic"):
    label = {
        "real_only (train)": "Real only (training split)",
        "real+all_synthetic": "Real + all synthetic",
        "real+filtered_synthetic": "Real + filtered synthetic",
    }[name]
    lines.append(f"| {label} | {percent(probe_synthetic[name]['test']['accuracy'])} | "
                 f"{percent(probe_synthetic[name]['test']['f1_macro'])} |")

lines.extend([
    "",
    "## Repeated-seed CNN ablation",
    "",
    "Mean ± population SD across five seeds. Validation accuracy selects the checkpoint; all "
    "test evaluations use the same real 79-image split.",
    "",
    "| Condition | n seeds | train real/syn | Val acc | Test acc | Test Top-5 | Test macro-F1 | "
    + " | ".join(f"R {c}" for c in CLASSES) + " |",
    "|" + "---|" * (7 + len(CLASSES)),
])
summary = {"runs": {}}
for name, rs in runs.items():
    t = [r["test"] for r in rs]
    row = {"n": len(rs), "test_acc": [x["accuracy"] for x in t], "f1": [x["f1_macro"] for x in t],
           "recall": {c: [x["per_class_recall"][c] for x in t] for c in CLASSES}}
    summary["runs"][name] = row
    lines.append(f"| {name} | {len(rs)} | {rs[0]['n_train_real']}/{rs[0]['n_train_synthetic']} | "
                 f"{ms([r['best_val_acc'] for r in rs])} | {ms(row['test_acc'])} | "
                 f"{ms([x['top5'] for x in t])} | {ms(row['f1'])} | "
                 + " | ".join(ms(row["recall"][c]) for c in CLASSES) + " |")

retrieval = read_json(os.path.join(RESULTS_DIR, "retrieval.json"))
lines.extend([
    "",
    "## Retrieval",
    "",
    "Index: real training images; queries: real test images; relevance: same class. Features are "
    "L2-normalised 1280-dimensional EfficientNet-B0 embeddings.",
    "",
    "| Feature model | P@1 | P@5 | P@10 |",
    "|---|---:|---:|---:|",
])
for name, label in (("a1_finetuned", "A1 fine-tuned EfficientNet-B0"),
                    ("deployed_frozen_probe", "Deployed frozen ImageNet probe")):
    row = retrieval[name]
    lines.append(f"| {label} | {percent(row['P@1'])} | {percent(row['P@5'])} | "
                 f"{percent(row['P@10'])} |")

synthetic_filter = read_json(os.path.join(RESULTS_DIR, "synthetic_filter.json"))
lines.extend([
    "",
    "## Synthetic-image filter counts",
    "",
    "Filter rule: the A1 real-data classifier must predict the intended class with confidence ≥ 0.5.",
    "",
    "| Class | Generated | Accepted |",
    "|---|---:|---:|",
])
summary["synthetic_filter"] = synthetic_filter
for cls in CLASSES:
    row = synthetic_filter[cls]
    lines.append(f"| {cls} | {row['generated']} | {row['accepted']} |")
lines.append(f"| **Total** | **{sum(x['generated'] for x in synthetic_filter.values())}** | "
             f"**{sum(x['accepted'] for x in synthetic_filter.values())}** |")

summary["cross_project"] = {
    "a1": a1,
    "linear_probe": probe,
    "retrieval": retrieval,
}
with open(os.path.join(RESULTS_DIR, "summary.md"), "w") as f:
    f.write("\n".join(lines) + "\n")
with open(os.path.join(RESULTS_DIR, "summary.json"), "w") as f:
    json.dump(summary, f, indent=1)
print("\n".join(lines))
